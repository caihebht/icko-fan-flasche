/* Normalisiert einen PMS-Code, z. B. "pms 485 c", "485 C", "Black 6 C" → "485C" / "BLACK6C". */
function normalizePms(raw) {
  return String(raw || "")
    .toUpperCase()
    .replace(/\bPMS\b/g, "")
    .replace(/[^A-Z0-9]/g, "");
}

